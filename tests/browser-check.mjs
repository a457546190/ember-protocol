import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const entry = process.argv[2] || 'http://127.0.0.1:5173/';
await page.goto(`${entry}?debug`, { waitUntil: 'networkidle' });
await page.locator('h1').waitFor();
await page.screenshot({ path: 'test-results/01-menu.png' });
await page.getByRole('button', { name: '行动指南' }).click();
await page.getByRole('heading', { name: '活下去，然后变强。' }).waitFor();
await page.getByRole('button', { name: '准备就绪' }).click();
await page.getByRole('button', { name: '开始行动' }).click();
await page.keyboard.down('d');
await page.waitForTimeout(700);
await page.keyboard.press('Space');
await page.waitForTimeout(300);
await page.keyboard.up('d');
const movement = await page.evaluate(() => ({ x: window.__ember.sim.world.x[0], dash: window.__ember.sim.dashCooldown }));
if (movement.x < 100 || movement.dash <= 0) throw new Error('Movement / dash did not execute');
await page.keyboard.press('Escape');
await page.getByRole('heading', { name: '喘息片刻。' }).waitFor();
const frozen = await page.evaluate(() => window.__ember.sim.time);
await page.waitForTimeout(300);
if (await page.evaluate(() => window.__ember.sim.time) !== frozen) throw new Error('Pause did not freeze time');
await page.getByRole('button', { name: '继续行动' }).click();
await page.evaluate(() => { window.__ember.sim.xp = window.__ember.sim.xpRequired; window.__ember.sim.checkLevel(); });
await page.getByRole('heading', { name: '余烬，正在觉醒。' }).waitFor();
await page.waitForTimeout(300);
await page.screenshot({ path: 'test-results/02-upgrade.png' });
await page.getByRole('button', { name: /公转环刃/ }).click();
if (await page.evaluate(() => window.__ember.sim.bladeCount) !== 1) throw new Error('First blade upgrade must grant exactly one blade');
await page.evaluate(() => {
  const s = window.__ember.sim;
  s.time = 59.99;
  window.__ember.step(1 / 60);
  if (!s.rangedIntroduced) throw new Error('Spitters were not introduced at one minute');
  const initial = [...s.world.query(64)];
  if (!initial.length) throw new Error('No ranged enemies at one minute');
  for (const id of initial) s.world.fireCooldown[id] = 10;
  const w = s.world;
  for (const [dx, dy] of [[310, -130], [-310, 110], [100, 285]]) {
    const id = s.spawnEnemy(4, 0, { x: w.x[0] + dx, y: w.y[0] + dy });
    w.hp[id] = w.maxHp[id] = 10000;
    w.fireCooldown[id] = 0;
  }
});
await page.waitForTimeout(170);
const telegraphs = await page.evaluate(() => [...window.__ember.sim.world.query(64)].filter(id => window.__ember.sim.world.windup[id] > 0).length);
if (telegraphs < 3) throw new Error('Ranged windup telegraphs are missing');
await page.screenshot({ path: 'test-results/15-ranged-telegraph.png' });
await page.waitForTimeout(800);
const enemyBullets = await page.evaluate(() => {
  const w = window.__ember.sim.world;
  return [...w.query(8)].filter(id => w.kind[id] === 1 && Math.abs(Math.hypot(w.vx[id], w.vy[id]) - 220) < 0.01).length;
});
if (enemyBullets < 3) throw new Error('Spitters failed to fire their red projectiles');
await page.screenshot({ path: 'test-results/16-ranged-projectiles.png' });
await page.evaluate(() => {
  const s = window.__ember.sim;
  s.upgrades.arc = 3; s.upgrades.multishot = 3; s.upgrades.haste = 3; s.upgrades.blades = 3;
  s.world.hp[0] = s.world.maxHp[0] = 1000;
  s.time = 80;
  for (let i = 0; i < 70; i++) s.spawnEnemy(i % 3, 150 + (i % 7) * 35);
});
await page.waitForTimeout(1800);
await page.screenshot({ path: 'test-results/03-combat.png' });
await page.evaluate(() => { const s = window.__ember.sim; s.status = 'playing'; s.xp = 0; s.time = 150; s.invulnerable = 100; });
await page.waitForTimeout(150);
const bossMaxHp = await page.evaluate(() => { const s = window.__ember.sim; return s.world.maxHp[s.bossId]; });
if (bossMaxHp !== 3600) throw new Error(`Boss HP must be doubled to 3600, got ${bossMaxHp}`);
await page.screenshot({ path: 'test-results/04-boss.png' });
await page.evaluate(() => { const s = window.__ember.sim; s.status = 'playing'; s.xp = 0; s.world.hp[0] = -100; });
await page.getByRole('heading', { name: '余烬，尚未熄灭。' }).waitFor();
await page.waitForTimeout(300);
await page.screenshot({ path: 'test-results/05-result.png' });
await page.getByRole('button', { name: '再次出发' }).click();
if (await page.evaluate(() => window.__ember.sim.kills) !== 0) throw new Error('Restart did not reset kills');
await page.evaluate(() => { const s = window.__ember.sim; s.bossDefeated = true; s.time = 180; s.invulnerable = 100; });
await page.getByRole('heading', { name: '火种，生生不息。' }).waitFor();
await page.waitForTimeout(300);
await page.screenshot({ path: 'test-results/06-victory.png' });
await page.getByRole('button', { name: '返回营地' }).click();
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(500);
await page.screenshot({ path: 'test-results/07-mobile-menu.png' });
await page.getByRole('button', { name: '开始行动' }).click();
await page.evaluate(() => { const s = window.__ember.sim; s.xp = s.xpRequired; s.checkLevel(); });
await page.getByRole('heading', { name: '余烬，正在觉醒。' }).waitFor();
await page.waitForTimeout(300);
await page.screenshot({ path: 'test-results/08-mobile-upgrade.png' });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
if (overflow) throw new Error('Mobile layout overflow');
await page.keyboard.press('1');
await page.waitForTimeout(150);
await page.screenshot({ path: 'test-results/09-mobile-game.png' });
if (errors.length) throw new Error(`Browser errors: ${errors.join('\n')}`);
console.log(JSON.stringify({ browser: 'Chrome', movement, firstBladeCount: 1, telegraphs, enemyBullets, bossMaxHp, screenshots: 11, mobileOverflow: overflow, errors }, null, 2));
await browser.close();
